"""
Infrastructure Agent

Specialized agent for Infrastructure as Code, cloud resource management,
Kubernetes orchestration, and cost optimization.
"""

from enum import Enum
from typing import Any

from .base_agent import BaseAgent
from src.core.tools.executor import ToolExecutor, get_tool_executor
from src.core.iac.generator import IaCGenerator


class CloudProvider(Enum):
    """Supported cloud providers."""
    AWS = "aws"
    GCP = "gcp"
    AZURE = "azure"


class IaCTool(Enum):
    """Infrastructure as Code tools."""
    TERRAFORM = "terraform"
    PULUMI = "pulumi"
    CLOUDFORMATION = "cloudformation"
    CDK = "cdk"


class InfrastructureAgent(BaseAgent):
    """
    Infrastructure-focused agent for cloud and IaC management.
    
    Capabilities:
    - Terraform/Pulumi management
    - Kubernetes orchestration
    - Cloud resource provisioning
    - Cost optimization
    - Disaster recovery planning
    - Network configuration
    - Dynamic IaC generation (mgx.dev recommendation)
    """
    
    def __init__(self, config=None):
        super().__init__(config)
        self._tool_executor = get_tool_executor()
        self._iac_generator = IaCGenerator(provider="cdktf")
    
    SYSTEM_PROMPT = """You are the Infrastructure Agent for DevOps Brain. Your mission is to 
manage and optimize cloud infrastructure with reliability and efficiency.

Your responsibilities:
1. Manage Infrastructure as Code (Terraform, Pulumi)
2. Orchestrate Kubernetes deployments
3. Provision and configure cloud resources
4. Optimize infrastructure costs
5. Plan and implement disaster recovery

Infrastructure principles:
- Infrastructure as Code for all resources
- Immutable infrastructure when possible
- Least privilege access
- Cost awareness in all decisions

A well-architected infrastructure enables the business to move fast safely."""

    def _register_handlers(self) -> None:
        """Register infrastructure action handlers."""
        self.register_handler("generate_terraform", self._generate_terraform)
        self.register_handler("plan_infrastructure", self._plan_infrastructure)
        self.register_handler("analyze_costs", self._analyze_costs)
        self.register_handler("kubernetes_deploy", self._kubernetes_deploy)
        self.register_handler("detect_drift", self._detect_drift)
        self.register_handler("plan_disaster_recovery", self._plan_disaster_recovery)
        self.register_handler("recommend_scaling", self._recommend_scaling)
    
    async def _get_system_prompt(self) -> str:
        return self.SYSTEM_PROMPT
    
